// Builds the CrazyGames upload: a self-contained folder + zip with relative paths,
// the CrazyGames SDK, and the address of your hosted duel server.
//
//   npm run build:crazygames -- wss://your-duel-server.onrender.com
//
// Output: dist/crazygames/ (folder) and dist/arcane-gambit-crazygames.zip (upload this).
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'dist', 'crazygames');
const ZIP = path.join(ROOT, 'dist', 'arcane-gambit-crazygames.zip');

const server = (process.argv[2] || process.env.DUEL_SERVER || '').trim();
if (!/^wss:\/\/[^\s/]+/.test(server)) {
  console.error('Usage: npm run build:crazygames -- wss://your-duel-server.example.com');
  console.error('(The duel server must use wss:// because CrazyGames pages are served over https.)');
  process.exit(1);
}

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
fs.cpSync(path.join(ROOT, 'public'), OUT, { recursive: true });
fs.cpSync(path.join(ROOT, 'shared'), path.join(OUT, 'shared'), { recursive: true });

// Point online duels at the hosted server.
fs.writeFileSync(path.join(OUT, 'js', 'config.js'),
  `// Generated by scripts/build-crazygames.mjs\nexport const DUEL_SERVER = ${JSON.stringify(server.replace(/\/$/, ''))};\n`);

// Add the CrazyGames SDK before the game script.
const indexPath = path.join(OUT, 'index.html');
let html = fs.readFileSync(indexPath, 'utf8');
html = html.replace('<script type="module" src="js/app.js"></script>',
  '<script src="https://sdk.crazygames.com/crazygames-sdk-v3.js"></script>\n  <script type="module" src="js/app.js"></script>');
fs.writeFileSync(indexPath, html);

// Sanity check: no absolute paths (CrazyGames requires relative ones).
const bad = [];
for (const f of walk(OUT)) {
  if (!/\.(js|html|css)$/.test(f)) continue;
  const text = fs.readFileSync(f, 'utf8');
  if (/(from|import\(|src=|href=)\s*['"]\/[^/]/.test(text) || /url\(['"]?\/[^/]/.test(text)) bad.push(path.relative(OUT, f));
}
if (bad.length) { console.error('Absolute paths found in:', bad.join(', ')); process.exit(1); }

writeZip(OUT, ZIP);
const files = walk(OUT);
const bytes = files.reduce((n, f) => n + fs.statSync(f).size, 0);
console.log(`Built ${files.length} files (${(bytes / 1024).toFixed(0)} KB) → ${path.relative(ROOT, OUT)}`);
console.log(`Upload this to CrazyGames: ${path.relative(ROOT, ZIP)} (${(fs.statSync(ZIP).size / 1024).toFixed(0)} KB)`);
console.log(`Duel server: ${server}`);

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : [p];
  });
}

// Minimal zip writer (deflate), so the build needs no extra dependencies.
function writeZip(dir, out) {
  const crcTable = Array.from({ length: 256 }, (_, n) => {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    return c >>> 0;
  });
  const crc32 = (buf) => {
    let c = 0xffffffff;
    for (const b of buf) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8);
    return (c ^ 0xffffffff) >>> 0;
  };
  const locals = [], centrals = [];
  let offset = 0;
  for (const file of walk(dir).sort()) {
    const name = Buffer.from(path.relative(dir, file).split(path.sep).join('/'));
    const data = fs.readFileSync(file);
    const comp = zlib.deflateRawSync(data, { level: 9 });
    const crc = crc32(data);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4); local.writeUInt16LE(0x0800, 6);
    local.writeUInt16LE(8, 8); local.writeUInt16LE(0, 10); local.writeUInt16LE(0x21, 12);
    local.writeUInt32LE(crc, 14); local.writeUInt32LE(comp.length, 18); local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(name.length, 26); local.writeUInt16LE(0, 28);
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0); central.writeUInt16LE(20, 4); central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0x0800, 8); central.writeUInt16LE(8, 10); central.writeUInt16LE(0, 12);
    central.writeUInt16LE(0x21, 14); central.writeUInt32LE(crc, 16); central.writeUInt32LE(comp.length, 20);
    central.writeUInt32LE(data.length, 24); central.writeUInt16LE(name.length, 28);
    central.writeUInt32LE(offset, 42);
    locals.push(local, name, comp);
    centrals.push(central, name);
    offset += local.length + name.length + comp.length;
  }
  const cd = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(centrals.length / 2, 8); end.writeUInt16LE(centrals.length / 2, 10);
  end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(offset, 16);
  fs.writeFileSync(out, Buffer.concat([...locals, cd, end]));
}
